def valeurs_juridictions():
    values = set()
    for _groupe, options in JURIDICTIONS_GROUPEES:
        for value, _label in options:
            values.add(value)
    return values


def choix_tribunal(valeur_existante=None):
    choices = [('', '— Choisir une juridiction —')]
    choices.extend(JURIDICTIONS_GROUPEES)
    if valeur_existante and valeur_existante not in valeurs_juridictions():
        choices.append(('Autre', [(valeur_existante, valeur_existante)]))
    return choices
